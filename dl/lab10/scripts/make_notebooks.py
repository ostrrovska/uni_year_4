def code(text):
    return nbf.v4.new_code_cell(text)


def fill(text, **subs):
    for key, value in subs.items():
        text = text.replace(f"@@{key.upper()}@@", str(value))
    return text


# ------------------------------------------------------------------ Завдання 1
def fill_blanks(nb, solutions, **subs):
    """Замінює вміст кожного блоку START/END відповідним розв'язком.

    Блок шукається за іменем функції, у чиєму тілі він лежить, тож порядок
    клітинок у базовому ноутбуці значення не має. Блок поза функцією
    (у Завданні 5 таким є завантаження CSV, уже заповнене викладачем)
    пропускається, якщо розв'язку для нього не задано.
    """
    filled = set()
    for cell in nb.cells:
        if cell.cell_type != "code" or START not in cell.source:
            continue

        m = re.search(r"^def (\w+)\(", cell.source, re.M)
        key = m.group(1) if m else None
        if key not in solutions:
            if key is None:
                continue          # блок поза функцією і без розв'язку — лишаємо як є
            raise ValueError(f"немає розв'язку для {key}")

        body = fill(solutions[key], **subs).strip("\n")
        before, rest = cell.source.split(START, 1)
        _, after = rest.split(END, 1)
        # Відступ закривального маркера беремо з оригіналу, щоб не ламати
        # вигляд клітинки: у різних ноутбуках він то два пробіли, то чотири.
        indent = re.search(r"([ \t]*)" + re.escape(END), rest).group(1)
        cell.source = f"{before}{START}\n{body}\n{indent}{END}{after}"
        filled.add(key)

    missing = set(solutions) - filled
    if missing:
        raise ValueError(f"не знайдено блоків для: {sorted(missing)}")
    return nb


def task1_notebook():
    """Базовий ноутбук Завдання 1 із заповненими пропусками."""
    nb = nbf.read(BASE_DIR / "Lab_10_1_Assignment.ipynb", as_version=4)
    before = len(nb.cells)
    fill_blanks(nb, C.SOLUTIONS, size=150)
    assert len(nb.cells) == before, "кількість клітинок змінилась — так не можна"
    return nb


# ------------------------------------------------------------------ Завдання 5
def clear_outputs(nb):
    """Прибирає чужі виводи з базового ноутбука.

    У копії Lab_10_5 від викладача лишилися виводи двох клітинок. Здавати
    треба результати власного прогону, тому чистимо — інакше ноутбук виглядає
    виконаним ще до запуску.
    """
    for cell in nb.cells:
        if cell.cell_type == "code":
            cell["outputs"] = []
            cell["execution_count"] = None
    return nb


