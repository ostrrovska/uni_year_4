// ------------------------------------------------------------------ boot
async function boot() {
  let data;
  try {
    const res = await fetch(`${DATA_URL}?t=${Date.now()}`, { cache: 'no-store' });
    if (!res.ok) throw new Error(String(res.status));
    data = await res.json();
  } catch {
    $('generated-at').textContent =
      'ui/data/lab5.json is missing - run ./scripts/lab5_run.ps1 and then python -m scripts.render_lab5_results';
    document.querySelectorAll('main .card').forEach((card) => card.classList.add('stale'));
    return;
  }

  renderBaseline(data);
  renderThroughput(data);
  renderLatency(data);
  renderKnee(data);
  renderScaling(data);
  renderCache(data);
  renderPool(data);
  renderTimeline(data);
  renderOpen(data);

  // Re-render on a resize only when the width band changed: the SVGs scale by viewBox, so a
  // redraw is needed for the label-collision pass, not for the geometry.
  let band = window.innerWidth > 560;
  window.addEventListener('resize', () => {
    const now = window.innerWidth > 560;
    if (now !== band) {
      band = now;
      renderThroughput(data);
      renderLatency(data);
      renderKnee(data);
    }
  });
}

document.addEventListener('click', (event) => {
  const button = event.target.closest('button.copy');
  if (!button) return;
  const pre = button.parentElement.querySelector('pre.cmd');
  if (!pre) return;
  navigator.clipboard?.writeText(pre.textContent).then(() => {
    button.textContent = 'Copied';
    setTimeout(() => { button.textContent = 'Copy'; }, 1200);
  }).catch(() => { button.textContent = 'Copy failed'; });
});

$('live-go').addEventListener('click', liveStart);
liveProbe();
boot();
