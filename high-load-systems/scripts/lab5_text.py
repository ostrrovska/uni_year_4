def translator(lang: str):
    """Return a lookup for one language that raises on a missing key.

    Raising rather than falling back: a key that silently renders as an empty string produces a
    document that looks finished and is not, and nobody re-reads a generated file closely enough
    to notice the hole.
    """
    if lang not in TEXT:
        raise KeyError(f"unknown language {lang!r}; have {sorted(TEXT)}")
    table = TEXT[lang]

    def t(key: str, **kwargs: object) -> str:
        if key not in table:
            raise KeyError(f"missing {lang} text for {key!r}")
        value = table[key]
        return value.format(**kwargs) if kwargs else value

    return t


def check_parity() -> list[str]:
    """Every key must exist in every language. Called by the renderer before it writes."""
    languages = list(TEXT)
    keys = {lang: set(TEXT[lang]) for lang in languages}
    every = set().union(*keys.values())
    problems = []
    for lang in languages:
        for key in sorted(every - keys[lang]):
            problems.append(f"{lang} is missing {key!r}")
    return problems
