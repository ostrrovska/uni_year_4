function renderTimeline(data) {
  const series = data.timelines || {};
  const keys = Object.keys(series);
  if (!keys.length) {
    $('timeline-section').hidden = true;
    return;
  }
  const select = $('timeline-pick');
  select.innerHTML = '';
  for (const key of keys) {
    const option = document.createElement('option');
    option.value = key;
    option.textContent = `Scenario ${SCENARIO_NAME[key]}`;
    select.appendChild(option);
  }
  // Set the value explicitly instead of relying on a <select> adopting its first option's
  // value implicitly. It does, in a browser - but the first draw then depends on that
  // behaviour rather than on anything this file states, and a headless run of this module
  // produced three empty charts because of it.
  select.value = keys[0];
  const draw = () => {
    const points = series[select.value] || [];
    // Three stacked panels on one x-axis: virtual users, throughput, tail latency. One unit
    // each - the staircase in the top panel is the ramp, and what the two panels below it do
    // at each step is the saturation argument.
    lineChart($('chart-tl-vus'), {
      series: [{ slot: 3, name: 'VUs', unit: '', xUnit: ' s', points: points.map((p) => ({ t: p.t, y: p.vus })) }],
      xKey: 't', xLabel: '', yLabel: 'virtual users', width: 620, height: 130,
    });
    lineChart($('chart-tl-rps'), {
      series: [{ slot: 1, name: 'req/s', unit: ' req/s', xUnit: ' s', points: points.map((p) => ({ t: p.t, y: p.rps })) }],
      xKey: 't', xLabel: '', yLabel: 'requests / second', width: 620, height: 150,
    });
    lineChart($('chart-tl-lat'), {
      series: [
        { slot: 1, name: 'p50', unit: ' ms', xUnit: ' s', points: points.map((p) => ({ t: p.t, y: p.p50 })) },
        { slot: 2, name: 'p95', unit: ' ms', xUnit: ' s', points: points.map((p) => ({ t: p.t, y: p.p95 })) },
        { slot: 3, name: 'p99', unit: ' ms', xUnit: ' s', points: points.map((p) => ({ t: p.t, y: p.p99 })) },
      ],
      xKey: 't', xLabel: 'seconds into the run', yLabel: 'latency ms (log)', log: true,
      width: 620, height: 180,
    });
  };
  select.addEventListener('change', draw);
  draw();
  takeaway('tl-takeaway', data, 'tl.chart_conclusion');
}

