// Lab5 - the report page's charts, drawn as inline SVG from ui/data/lab5.json.
//
// No chart library and no build step, for the same reason the rest of this UI has neither:
// nginx serves ./ui from a read-only bind mount, and a CDN <script> would make a page whose
// whole claim is "it runs beside the system it describes" depend on the open internet.
//
// Every number here comes from scripts/render_lab5_results.py, which generates both this
// file's data and docs/lab5-results.md from the same pass over docs/loadtest/lab5/*.json. The
// page cannot disagree with the document, because neither of them holds a number of its own.
//
// Chart rules this file follows, and the reason each one is not negotiable:
//   - One y-axis per panel. Two measures of different units get two stacked panels sharing the
//     x-axis, never two scales on one frame.
//   - Colour follows the entity. Scenario A is always series-1, B series-2, C series-3; p50 /
//     p95 / p99 keep their slots in every panel. A filter that drops a series never repaints
//     the survivors.
//   - A legend whenever two or more series are plotted, *plus* a direct label at each series'
//     right end, *plus* a collapsed table of the same numbers. --series-3 (#1baf7a) measures
//     2.74:1 against the light surface, under the 3:1 floor, so identity may never rest on the
//     hue alone - the label and the table are the required relief.
//   - Values and labels wear text tokens, never the series colour.

