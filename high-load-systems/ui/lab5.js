// ------------------------------------------------------------------ live demo
const live = {
  timer: null,
  points: [],
  running: false,
};

async function liveProbe() {
  try {
    const res = await fetch(`${LIVE_BASE}/status`, { cache: 'no-store' });
    if (!res.ok) throw new Error(String(res.status));
    const body = await res.json();
    $('live-state').textContent = `runner ready - ${body.profile || 'short ladder'}`;
    $('live-state').className = 'live-state on';
    $('live-go').disabled = false;
    return true;
  } catch {
    // The page degrades to the command rather than to an error: this is a defence prop, and a
    // prop that cannot be started must still tell you how to start it.
    $('live-state').textContent = 'runner offline - start it with the command below';
    $('live-state').className = 'live-state off';
    $('live-go').disabled = true;
    return false;
  }
}

async function liveStart() {
  $('live-go').disabled = true;
  live.points = [];
  live.running = true;
  try {
    await fetch(`${LIVE_BASE}/run`, { method: 'POST' });
  } catch {
    $('live-state').textContent = 'runner did not accept the request';
    $('live-state').className = 'live-state off';
    live.running = false;
    $('live-go').disabled = false;
    return;
  }
  $('live-state').textContent = 'running - 10 -> 50 -> 100 VUs, about 60 s';
  $('live-state').className = 'live-state on';
  if (live.timer) clearInterval(live.timer);
  live.timer = setInterval(livePoll, 500);
}

async function livePoll() {
  let body;
  try {
    const res = await fetch(`${LIVE_BASE}/live`, { cache: 'no-store' });
    body = await res.json();
  } catch {
    return;
  }
  live.points = body.points || [];
  drawLive(body);
  if (body.state === 'finished' || body.state === 'failed') {
    clearInterval(live.timer);
    live.timer = null;
    live.running = false;
    $('live-go').disabled = false;
    $('live-state').textContent = body.state === 'finished'
      ? `finished - ${fmt(body.summary ? body.summary.requests : 0, 0)} requests, peak ${fmt(body.peak_rps)} req/s`
      : 'the run failed - see the terminal running the runner';
    $('live-state').className = `live-state ${body.state === 'finished' ? 'on' : 'off'}`;
  }
}

